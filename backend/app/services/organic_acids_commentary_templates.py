from __future__ import annotations

from typing import Any, Dict, List


def _s(x: Any) -> str:
    return str(x or "").strip()


def _low(x: Any) -> str:
    return _s(x).lower().replace("ё", "е")


def _domain_from_group(group_name: str) -> str:
    low = _low(group_name)
    if "энерг" in low:
        return "energy"
    if "β-окис" in low or "жир" in low:
        return "beta_oxidation"
    if "витамин" in low or "кофактор" in low:
        return "cofactors"
    if "внеш" in low or "ксенобиот" in low or "детокс" in low:
        return "xenobiotics"
    if "глутатион" in low or "окислитель" in low:
        return "glutathione"
    if "азот" in low or "оротов" in low:
        return "nitrogen_cycle"
    return "other"


def build_marker_comment(
    *,
    marker_name: str,
    flag: str,
    group_name: str = "",
    source_note: str = "",
) -> str:
    """
    Профессиональный короткий комментарий к отдельному маркеру.
    Важно:
    - 1–2 предложения
    - без назначения лечения
    - без списка добавок
    - с нормальной клинической осторожностью
    """
    name = _s(marker_name)
    low_name = _low(marker_name)
    flag_low = _low(flag)
    group_key = _domain_from_group(group_name)

    direction = "изменение"
    if flag_low == "high":
        direction = "повышение"
    elif flag_low == "low":
        direction = "снижение"

    if "пироглутам" in low_name:
        base = (
            f"{direction.capitalize()} пироглутаминовой кислоты может встречаться при изменении "
            f"глутатионового обмена и повышенной окислительной нагрузке."
        )
        tail = " Изолированно показатель неспецифичен и требует оценки в клиническом контексте."
        return (base + tail).strip()

    if "пиколинов" in low_name:
        base = (
            f"{direction.capitalize()} пиколиновой кислоты может отражать сдвиг триптофанового пути "
            f"и иммунно-воспалительный контекст."
        )
        tail = " Сам по себе показатель не позволяет делать вывод о конкретной патологии."
        return (base + tail).strip()

    if "квинолинов" in low_name:
        base = (
            f"{direction.capitalize()} квинолиновой кислоты может соответствовать изменению триптофанового пути "
            f"и требует интерпретации вместе с общим клиническим фоном."
        )
        tail = " Изолированно не является специфичным диагностическим признаком."
        return (base + tail).strip()

    if "формиминоглутам" in low_name:
        base = (
            f"{direction.capitalize()} формиминоглутаминовой кислоты может встречаться при нарушении "
            f"отдельных витаминно-коферментных звеньев обмена."
        )
        tail = " Клиническая значимость определяется только после очной оценки и сопоставления с другими данными."
        return (base + tail).strip()

    if "метилмалон" in low_name:
        base = (
            f"{direction.capitalize()} метилмалоновой кислоты может требовать оценки контекста дефицитных состояний, "
            f"включая B12-зависимые звенья обмена."
        )
        tail = " Показатель не должен интерпретироваться изолированно."
        return (base + tail).strip()

    if "ксантурен" in low_name:
        base = (
            f"{direction.capitalize()} ксантуреновой кислоты может встречаться при изменении "
            f"триптофанового пути и кофакторного обеспечения."
        )
        tail = " Требуется клиническая корреляция."
        return (base + tail).strip()

    if "малонов" in low_name:
        base = (
            f"{direction.capitalize()} малоновой кислоты может быть связано с особенностями энергетического "
            f"и жирового обмена."
        )
        tail = " Интерпретация зависит от режима питания, симптомов и других метаболических маркеров."
        return (base + tail).strip()

    if any(k in low_name for k in ["суберинов", "себацинов", "адипинов", "этилмалон"]):
        base = (
            f"{direction.capitalize()} {name.lower()} может встречаться при изменении β-окисления жирных кислот "
            f"или энергетического обмена."
        )
        tail = " Такой сдвиг требует оценки вместе с остальными маркерами профиля."
        return (base + tail).strip()

    if "оротов" in low_name:
        base = (
            f"{direction.capitalize()} оротовой кислоты требует осторожной оценки в контексте азотистого обмена "
            f"и сопутствующих лабораторных данных."
        )
        tail = " По одному этому показателю сильные выводы недопустимы."
        return (base + tail).strip()

    if any(k in low_name for k in ["гиппур", "метилгиппур", "миндальн", "фенилглиокс", "бензойн", "трикарбал"]):
        base = (
            f"{direction.capitalize()} {name.lower()} может соответствовать внешней метаболической нагрузке "
            f"или особенностям детоксикации."
        )
        tail = " Оценка должна учитывать лекарства, питание, БАДы и возможные бытовые/производственные экспозиции."
        return (base + tail).strip()

    # Общие шаблоны по доменам
    if group_key == "energy":
        return (
            f"{direction.capitalize()} {name.lower()} может отражать изменение энергетического обмена. "
            f"Показатель следует интерпретировать только вместе с клиническими данными и другими метаболическими маркерами."
        )

    if group_key == "beta_oxidation":
        return (
            f"{direction.capitalize()} {name.lower()} может быть связано с изменением обмена жирных кислот. "
            f"Изолированно показатель неспецифичен."
        )

    if group_key == "cofactors":
        return (
            f"{direction.capitalize()} {name.lower()} может встречаться при изменении витаминно-коферментных звеньев обмена. "
            f"Клиническая значимость требует подтверждения."
        )

    if group_key == "xenobiotics":
        return (
            f"{direction.capitalize()} {name.lower()} может соответствовать внешней метаболической нагрузке. "
            f"При интерпретации важно учитывать внешние факторы и анамнез."
        )

    if group_key == "glutathione":
        return (
            f"{direction.capitalize()} {name.lower()} может отражать сдвиг антиоксидантного статуса. "
            f"Сам по себе показатель не является диагностическим."
        )

    if group_key == "nitrogen_cycle":
        return (
            f"{direction.capitalize()} {name.lower()} может требовать оценки азотистого обмена. "
            f"По одному маркеру окончательные выводы невозможны."
        )

    if source_note:
        return (
            f"{direction.capitalize()} {name.lower()}. "
            f"{_s(source_note)} "
            f"Клиническая значимость определяется только после очной интерпретации."
        ).strip()

    return (
        f"{direction.capitalize()} {name.lower()} следует интерпретировать в контексте жалоб, анамнеза "
        f"и остальных показателей профиля."
    )


def build_group_interpretation(
    *,
    group_name: str,
    marker_names: List[str],
) -> str:
    """
    Более профессиональная интерпретация группы маркеров.
    Без лечения в лоб. Без перегруза добавками.
    """
    group = _s(group_name)
    domain = _domain_from_group(group_name)
    joined = ", ".join(_s(x) for x in (marker_names or []) if _s(x))

    if domain == "energy":
        return (
            "Сочетание отклонений в этой группе может соответствовать изменению энергетического обмена. "
            "Такой паттерн следует сопоставлять с режимом питания, переносимостью интервалов между едой, общим самочувствием "
            "и другими метаболическими маркерами. Изолированно группа не определяет конкретную патологию."
        )

    if domain == "beta_oxidation":
        return (
            "Сочетание отклонений в этой группе может соответствовать изменению β-окисления жирных кислот. "
            "Клиническая значимость определяется после оценки общего метаболического контекста, питания и сопутствующих данных. "
            "Коррекционные меры могут обсуждаться только после очной интерпретации."
        )

    if domain == "cofactors":
        return (
            "Отклонения в этой группе могут встречаться при изменении витаминно-коферментного обеспечения обмена. "
            "Такой паттерн неспецифичен и требует подтверждения через клиническую оценку, рацион и, при необходимости, "
            "дополнительные лабораторные данные."
        )

    if domain == "xenobiotics":
        return (
            "Отклонения в этой группе могут соответствовать внешней метаболической нагрузке или особенностям детоксикации. "
            "При интерпретации важно учитывать лекарства, БАДы, бытовые и производственные воздействия, а также рацион."
        )

    if domain == "glutathione":
        return (
            "Такая группа может отражать изменение антиоксидантного статуса и глутатионового обмена. "
            "Значимость паттерна определяется только вместе с остальными лабораторными и клиническими данными."
        )

    if domain == "nitrogen_cycle":
        return (
            "Эта группа требует особенно осторожной оценки, поскольку может касаться азотистого обмена. "
            "По одному или нескольким маркерам без клинического контекста делать сильные выводы недопустимо."
        )

    return (
        f"Отклонения в группе «{group}» требуют клинической корреляции. "
        f"Интерпретация должна учитывать симптомы, анамнез и сопутствующие лабораторные данные."
    )


def build_hypothesis_comment(
    *,
    hypothesis: str,
) -> str:
    """
    Комментарий к рабочей гипотезе.
    Никаких назначений. Только смысл и что делать дальше.
    """
    low = _low(hypothesis)

    if "энергетического и жирового обмена" in low:
        return (
            "Эта гипотеза основана на сочетании маркеров, которые могут отражать изменение энергетического и жирового обмена. "
            "Подтверждение возможно только после сопоставления с клинической картиной и дополнительными данными."
        )

    if "кофакторной" in low or "витаминной" in low:
        return (
            "Гипотеза отражает возможный вклад витаминно-коферментных факторов. "
            "Она требует подтверждения через рацион, анамнез и, при необходимости, дополнительные исследования."
        )

    if "внешней метаболической нагрузки" in low:
        return (
            "Гипотеза предполагает возможное влияние внешних факторов. "
            "Для её оценки важно учитывать лекарства, БАДы, бытовые и производственные экспозиции."
        )

    if "окислительный стресс" in low or "глутатион" in low:
        return (
            "Гипотеза указывает на возможный сдвиг антиоксидантного статуса. "
            "Изолированно такой вывод носит ориентировочный характер."
        )

    if "азотистого обмена" in low:
        return (
            "Эта гипотеза требует особенно осторожной оценки и не должна интерпретироваться как подтверждённая патология "
            "без дополнительных клинических оснований."
        )

    return (
        "Это рабочая гипотеза, а не диагноз. "
        "Её значимость определяется только после клинической оценки и сопоставления с другими данными."
    )


def build_followup_comment(
    *,
    direction: str,
    check: str,
) -> str:
    """
    Профессиональная подводка к follow-up.
    Можно использовать рядом с блоком 'что проверить дальше'.
    """
    low_dir = _low(direction)
    low_check = _low(check)

    if "консультац" in low_dir:
        return "Первый шаг — очная клиническая интерпретация результата."
    if "энерг" in low_dir:
        return "Это направление помогает уточнить, связан ли паттерн с особенностями питания и энергетического обмена."
    if "кофактор" in low_dir:
        return "Это направление позволяет оценить возможный вклад витаминно-коферментных факторов."
    if "экспозици" in low_dir:
        return "Это направление помогает проверить роль внешних факторов и метаболической нагрузки."
    if "окислитель" in low_dir or "глутатион" in low_dir:
        return "Это направление нужно для оценки возможной клинической значимости антиоксидантного контекста."
    if "азот" in low_dir:
        return "Это направление рассматривается только при наличии клинических оснований."
    if "контроль" in low_dir or "повтор" in low_check:
        return "Повторная оценка может быть полезна для понимания стойкости или временности изменений."

    return "Это направление дообследования обсуждается по результатам очной оценки."


