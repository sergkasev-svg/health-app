"""
Живой AI-консьерж «Михаил»: пошаговый диалог после анализа.
Этапы: понять анализ → уточнить слабые места → вывод → продажа (персональный план).
"""
from __future__ import annotations

from typing import Any, Dict


def _detect_risk_from_input(user_input: str) -> str:
    """По ответу пользователя уточняем риск для персонализации вывода."""
    if not user_input or not isinstance(user_input, str):
        return ""
    t = user_input.lower().strip()
    if "температур" in t or "температура" in t or "лихорадк" in t or "горяч" in t:
        return "воспаление"
    if "слабост" in t or "усталост" in t or "утомля" in t:
        return "слабость"
    if "стресс" in t or "болел" in t or "недавно болел" in t:
        return "стресс_или_болезнь"
    if "хроническ" in t or "диабет" in t or "давление" in t or "сердце" in t:
        return "хроническое"
    return ""


def run_mikhail_consultation(
    result: Dict[str, Any],
    user_input: str,
    state: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Один шаг диалога с Михаилом.
    result — результат multi-lab (анализ), user_input — сообщение пользователя, state — этап и накопленные риски.
    Возвращает { "text": str, "state": dict }.
    """
    stage = state.get("stage", "start")
    risk = state.get("risk") or _detect_risk_from_input(user_input)
    if risk:
        state["risk"] = risk

    # ========================
    # СТАРТ
    # ========================
    if stage == "start":
        state["stage"] = "questions"
        return {
            "text": (
                "Здравствуйте, я ваш консультант Михаил.\n\n"
                "Я посмотрел ваш анализ.\n"
                "Есть момент, который стоит уточнить.\n\n"
                "Скажите:\n"
                "- Есть ли сейчас слабость или усталость?\n"
                "- Бывает ли температура или ощущение воспаления?"
            ),
            "state": state,
        }

    # ========================
    # УТОЧНЕНИЕ
    # ========================
    if stage == "questions":
        state["stage"] = "analysis"
        risk_line = ""
        if risk == "воспаление":
            risk_line = "\n👉 Есть признаки воспалительного процесса — имеет смысл проверить CRP и динамику.\n\n"
        elif risk == "слабость":
            risk_line = "\n👉 Учитывая слабость, стоит повторить ОАК и при необходимости расширить обследование.\n\n"
        return {
            "text": (
                "Понял.\n\n"
                "С учётом вашего ответа:\n"
                "- серьёзного лабораторного паттерна нет\n"
                "- повышение СОЭ выглядит как неспецифическая реакция\n"
                f"{risk_line}"
                "Теперь важно понять — это разово или системно.\n\n"
                "Скажите:\n"
                "- недавно болели или был стресс?\n"
                "- есть хронические заболевания?"
            ),
            "state": state,
        }

    # ========================
    # ВЫВОД
    # ========================
    if stage == "analysis":
        state["stage"] = "final"
        risk_note = ""
        if risk == "воспаление":
            risk_note = "\n👉 Есть признаки воспалительного процесса — рекомендую CRP и повтор ОАК через 2–4 недели.\n\n"
        elif risk == "хроническое":
            risk_note = "\n👉 На фоне хронических заболеваний динамика анализов важна — лучше вести дневник и повторять ОАК по плану.\n\n"
        return {
            "text": (
                "Сейчас картина выглядит спокойно.\n\n"
                "👉 Вероятнее всего:\n"
                "- это не опасное отклонение\n"
                "- а временная реакция организма\n\n"
                f"{risk_note}"
                "📌 Что делать:\n"
                "- ничего срочного не требуется\n"
                "- можно проверить CRP\n"
                "- повторить анализ позже\n\n"
                "Но есть нюанс.\n"
                "Важно не пропустить системный процесс.\n"
            ),
            "state": state,
        }

    # ========================
    # ПРОДАЖА
    # ========================
    if stage == "final":
        return {
            "text": (
                "Я могу собрать для вас персональный план:\n\n"
                "- какие анализы реально нужны\n"
                "- как отслеживать динамику\n"
                "- когда это становится проблемой\n\n"
                "👉 Получить полный план"
            ),
            "state": state,
        }

    # fallback: вернуть на старт
    state["stage"] = "start"
    return run_mikhail_consultation(result, user_input or "", state)
