def _clean_spaces(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def _apply_replacements(text: str) -> str:
    out = text.lower().replace("ё", "е")
    for pattern, replacement in COLLOQUIAL_REPLACEMENTS.items():
        out = re.sub(pattern, replacement, out, flags=re.IGNORECASE)
    return _clean_spaces(out)


def detect_branch(text: str) -> str:
    text_l = (text or "").lower().replace("ё", "е")
    try:
        from app.services.symptom_cluster_engine import priority_triage
        priority = priority_triage(text_l)
        if priority:
            return priority
    except Exception:
        pass
    scores: dict[str, int] = {}
    for branch, keywords in BRANCH_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in text_l)
        if score:
            scores[branch] = score
    if not scores:
        return ""
    return max(scores.items(), key=lambda x: x[1])[0]


def normalize(text: str | None) -> dict[str, Any]:
    """Нормализация ввода: замены по словарю, определение ветки. Возвращает dict с raw_text, normalized_text, detected_branch."""
    raw = (text or "").strip()
    normalized = _apply_replacements(raw)
    branch = detect_branch(normalized)
    return {
        "raw_text": raw,
        "normalized_text": normalized,
        "detected_branch": branch,
    }


def normalize_to_string(text_or_payload: Any) -> str:
    """Обратная совместимость: возвращает только нормализованную строку (для вызовов, ожидающих str)."""
    if text_or_payload is None:
        return ""
    if isinstance(text_or_payload, str):
        return normalize(text_or_payload).get("normalized_text", text_or_payload.strip())
    if isinstance(text_or_payload, dict):
        for key in ("message", "text", "user_message", "query", "content"):
            val = text_or_payload.get(key)
            if isinstance(val, str) and val.strip():
                return normalize(val).get("normalized_text", val.strip())
    return normalize(str(text_or_payload)).get("normalized_text", str(text_or_payload))
