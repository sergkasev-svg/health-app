"""
NutritionAnalysisEngine: анализ рациона и общие рекомендации по питанию
(ВОЗ, сбалансированное распределение макро/микро, средиземноморская диета, соль/сахар).
Рекомендации только общие, не заменяют консультацию диетолога. Изолированный модуль.
"""
from typing import Any

GUIDELINES = {
    "description": "Общие рекомендации по питанию на основе гайдлайнов ВОЗ и доказательной нутрициологии.",
    "balance": [
        "Сбалансированное соотношение белков, жиров и углеводов; приоритет цельнозерновым, овощам и фруктам.",
        "Достаточное количество белка: бобовые, рыба, птица, яйца, при необходимости — молочные продукты.",
        "Полезные жиры: орехи, семена, растительные масла, жирная рыба (омега-3).",
    ],
    "increase": [
        "Больше свежих овощей и фруктов (не менее 400 г в день по ВОЗ).",
        "Цельнозерновые продукты вместо рафинированных.",
        "Достаточное количество воды (ориентир — жажда и цвет мочи).",
    ],
    "warnings": [
        "Ограничить добавленный сахар и соль (ВОЗ: сахар <10% калорий, соль <5 г/день).",
        "Избегать избытка трансжиров и ультрапереработанных продуктов.",
        "Умеренность в кофеине и алкоголе; при вопросах пользователя — общие рамки, не назначение.",
    ],
    "mindful": [
        "Осознанное питание: медленное пережёвывание, внимание к сигналам голода и сытости.",
    ],
}


def get_nutrition_recommendations(
    context_text: str = "",
    include_deficit_hints: bool = True,
) -> dict[str, Any]:
    """
    Возвращает структурированные общие рекомендации по питанию.
    context_text может содержать упоминания дефицита (железо, D, B12) — тогда добавляются подсказки.
    """
    out: dict[str, Any] = {
        "summary": GUIDELINES["description"],
        "balance": list(GUIDELINES["balance"]),
        "increase": list(GUIDELINES["increase"]),
        "warnings": list(GUIDELINES["warnings"]),
        "mindful": list(GUIDELINES["mindful"]),
        "deficit_hints": [],
    }
    if not include_deficit_hints or not context_text:
        return out
    lower = (context_text or "").lower()
    if "желез" in lower or "анеми" in lower or "гемоглобин" in lower:
        out["deficit_hints"].append("При дефиците железа: источники гемового железа (мясо, печень, рыба), витамин C для усвоения, ограничить чай/кофе во время еды.")
    if "витамин d" in lower or "витамина d" in lower or "дефицит d" in lower:
        out["deficit_hints"].append("Витамин D: пребывание на солнце (с защитой кожи), жирная рыба, обогащённые продукты; при дефиците — дозу определяет врач.")
    if "b12" in lower or "витамин b12" in lower or "кобаламин" in lower:
        out["deficit_hints"].append("B12: животные продукты, обогащённые крупы; при дефиците — обследование и назначение врача.")
    if "магний" in lower or "магни" in lower:
        out["deficit_hints"].append("Магний: зелёные листовые овощи, орехи, семена, бобовые; при клиническом дефиците — по назначению врача.")
    return out
