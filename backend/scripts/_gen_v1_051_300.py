def _scenario_num(case_id: str) -> int | None:
    if not case_id.startswith("v1-"):
        return None
    parts = case_id.split("-")
    if len(parts) < 2 or not parts[1].isdigit():
        return None
    return int(parts[1], 10)


def main() -> None:
    lines = CASES.read_text(encoding="utf-8").splitlines()
    # Keep v1-001..v1-050 only; drop any previously appended v1-051+ block.
    keep: list[str] = []
    for ln in lines:
        if not ln.strip():
            continue
        row = json.loads(ln)
        eid = str(row.get("id") or "")
        num = _scenario_num(eid)
        if num is None or num <= 50:
            keep.append(ln)

    out: list[str] = []
    for n in range(51, 301):
        turns = TEMPLATES[(n - 51) % len(TEMPLATES)]
        for channel, suf in (("chat", "chat"), ("voice-structured", "voice")):
            row = {
                "id": f"v1-{n:03d}-{suf}",
                "channel": channel,
                "user_id": f"clinical-v1-{n:03d}-{suf}",
                "turns": list(turns),
            }
            out.append(json.dumps(row, ensure_ascii=False))
    CASES.write_text("\n".join(keep) + "\n" + "\n".join(out) + "\n", encoding="utf-8")
    print(f"Rewrote tail: kept {len(keep)} lines, appended {len(out)}, total {len(keep)+len(out)}")


if __name__ == "__main__":
    main()
