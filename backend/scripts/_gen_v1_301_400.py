def _num_from_id(case_id: str) -> int | None:
    if not case_id.startswith("v1-"):
        return None
    p = case_id.split("-")
    if len(p) < 2 or not p[1].isdigit():
        return None
    return int(p[1], 10)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--rewrite",
        action="store_true",
        help="Удалить существующие v1-301..v1-400 и вставить заново из шаблонов T.",
    )
    args = ap.parse_args()

    lines = [ln for ln in CASES.read_text(encoding="utf-8").splitlines() if ln.strip()]
    if not args.rewrite:
        for ln in lines:
            if str(json.loads(ln).get("id")) == "v1-301-chat":
                print("v1-301-chat already present; no-op (use --rewrite to refresh)")
                return 0
    else:
        kept: list[str] = []
        for ln in lines:
            n = _num_from_id(str(json.loads(ln).get("id") or ""))
            if n is not None and 301 <= n <= 400:
                continue
            kept.append(ln)
        lines = kept
        print("rewrite: removed v1-301..v1-400 block from file")
    out: list[str] = []
    for n in range(301, 401):
        t = T[(n - 301) % len(T)]
        turns = list(t)
        for channel, suf in (("chat", "chat"), ("voice-structured", "voice")):
            row = {
                "id": f"v1-{n:03d}-{suf}",
                "channel": channel,
                "user_id": f"clinical-v1-{n:03d}-{suf}",
                "turns": list(turns),
            }
            out.append(json.dumps(row, ensure_ascii=False))
    CASES.write_text("\n".join(lines) + "\n" + "\n".join(out) + "\n", encoding="utf-8")
    print(f"Appended {len(out)} lines; total {len(lines)+len(out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
