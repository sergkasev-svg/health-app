def _num_from_id(case_id: str) -> int | None:
    if not case_id.startswith("v1-"):
        return None
    p = case_id.split("-")
    if len(p) < 2 or not p[1].isdigit():
        return None
    return int(p[1], 10)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rewrite", action="store_true", help="Удалить v1-401..v1-500 и вставить заново.")
    args = ap.parse_args()

    lines = [ln for ln in CASES.read_text(encoding="utf-8").splitlines() if ln.strip()]

    if not args.rewrite:
        for ln in lines:
            if str(json.loads(ln).get("id")) == "v1-401-chat":
                print("v1-401-chat already present; no-op (use --rewrite to refresh)")
                return 0
    else:
        lines = [ln for ln in lines if not (401 <= (_num_from_id(str(json.loads(ln).get("id") or "")) or 0) <= 500)]
        print("rewrite: removed v1-401..v1-500 if present")

    if len(T) != 25:
        print("internal error: need 25 templates", file=sys.stderr)
        return 1

    out: list[str] = []
    for n in range(401, 501):
        t = T[(n - 401) % 25]
        for channel, suf in (("chat", "chat"), ("voice-structured", "voice")):
            out.append(
                json.dumps(
                    {
                        "id": f"v1-{n:03d}-{suf}",
                        "channel": channel,
                        "user_id": f"clinical-v1-{n:03d}-{suf}",
                        "turns": list(t),
                    },
                    ensure_ascii=False,
                )
            )
    CASES.write_text("\n".join(lines) + "\n" + "\n".join(out) + "\n", encoding="utf-8")
    print(f"Appended {len(out)} lines; total {len(lines)+len(out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
